const {
    normalizeAtlasBasePath,
    sanitizePackName,
    toCamelCase,
    toPascalCase,
} = require("../utils/path-utils");

/**
 * ============================================================================
 * Phaser TypeScript Source Generation
 * ============================================================================
 *
 * Restores the old generated runtime layer: typed asset metadata, helpers for
 * placing image/nine-slice objects, asset registry, and preview scene.
 */

/**
 * Builds a runtime atlas file URL from a normalized base path and file name.
 */
function buildAtlasFilePath(basePath, fileName) {
    const cleanFileName = String(fileName || "").replace(/^\/+/, "");
    return `${normalizeAtlasBasePath(basePath)}${cleanFileName}`;
}

/**
 * Creates a unique safe asset key for generated TypeScript object properties.
 */
function createUniqueAssetKey(rawName, used) {
    const base = toCamelCase(rawName);
    let next = base || "asset";
    let suffix = 2;

    while (used.has(next)) {
        next = `${base}${suffix}`;
        suffix += 1;
    }

    used.add(next);
    return next;
}

/**
 * Extracts nine-slice padding from names like "button.nine.20".
 */
function detectNinePadding(rawName) {
    const match = String(rawName || "").trim().match(/(?:^|[._-])nine\.(\d+)$/i);
    if (!match) return null;
    const parsed = Number(match[1]);
    if (!Number.isFinite(parsed)) return null;
    return parsed;
}

/**
 * Строит ключ object literal из имени слоя Figma.
 */
function buildObjectKey(rawName) {
    const key = String(rawName || "");
    if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key)) {
        return key;
    }

    return `'${key
        .replace(/\\/g, "\\\\")
        .replace(/'/g, "\\'")
        .replace(/\r/g, "\\r")
        .replace(/\n/g, "\\n")}'`;
}

/**
 * Строит обращение к полю children с учетом quoted keys.
 */
function buildObjectAccess(objectRef, rawName) {
    const key = String(rawName || "");
    if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key)) {
        return `${objectRef}.${key}`;
    }

    return `${objectRef}[${buildObjectKey(key)}]`;
}

/**
 * Converts manifest items into sorted generated asset entries.
 */
function buildAssetEntries(manifest) {
    const usedAssetKeys = new Set();
    const entries = manifest.items.map((item) => {
        const frameBaseName = String(item.fileName || "item.png").replace(/\.png$/i, "");
        const assetKey = createUniqueAssetKey(frameBaseName, usedAssetKeys);
        const kind = item.kind === "nine" ? "nine" : "image";
        const ninePadding = kind === "nine"
            ? (Number.isFinite(Number(item.ninePadding)) ? Number(item.ninePadding) : detectNinePadding(item.name || "") || 20)
            : undefined;

        return {
            assetKey,
            name: item.name || frameBaseName,
            kind,
            ninePadding,
            x: Number(item.x || 0),
            y: Number(item.y || 0),
            width: Number(item.width || 0),
            height: Number(item.height || 0),
            frameName: item.fileName,
        };
    });

    entries.sort((a, b) => {
        if (a.y !== b.y) return a.y - b.y;
        if (a.x !== b.x) return a.x - b.x;
        return a.assetKey.localeCompare(b.assetKey);
    });

    return entries;
}

/**
 * Generates the pack-specific asset registry and preload function.
 */
function buildAssetsTs(props) {
    const { entries, packName, packCamel, atlasPngUrl, atlasJsonUrl } = props;
    const assetsObjectLines = entries.map((entry) => {
        const ninePaddingLine = entry.kind === "nine" ? `\n    ninePadding: ${entry.ninePadding},` : "";
        return `  ${entry.assetKey}: {\n    name: ${JSON.stringify(String(entry.name || ""))},\n    url: "${atlasPngUrl}",\n    frameName: "${entry.frameName}",\n    width: ${entry.width},\n    height: ${entry.height},\n    x: ${entry.x},\n    y: ${entry.y},\n    kind: "${entry.kind}",${ninePaddingLine}\n  },`;
    });
    const orderLines = entries.map((entry) => `  "${entry.assetKey}",`);
    const preloadFunctionName = `preload${toPascalCase(packName)}Assets`;

    return `// This file is auto-generated by figma2assets plugin. Do not edit manually.

export const ${packCamel}AutoAssetsConst = {
${assetsObjectLines.join("\n")}
} as const;

export type AutoAssetName = keyof typeof ${packCamel}AutoAssetsConst;

export const ${packCamel}AutoAssetOrder: readonly AutoAssetName[] = [
${orderLines.join("\n")}
];

export const ${packCamel}AutoAssetsConfig = {
  images: ${packCamel}AutoAssetsConst,
  preload: {
    atlases: [
      {
        name: "${packName}",
        pngUrl: "${atlasPngUrl}",
        jsonUrl: "${atlasJsonUrl}",
      },
    ],
  },
} as const;

export const ${packCamel}AutoAssets = ${packCamel}AutoAssetsConfig.images;
export const ${packCamel}AutoAtlas = ${packCamel}AutoAssetsConfig.preload.atlases[0];

/**
 * Preloads the generated atlas for this pack.
 */
export function ${preloadFunctionName}(scene: Phaser.Scene): void {
  ${packCamel}AutoAssetsConfig.preload.atlases.forEach((atlas) => {
    if (scene.textures.exists(atlas.pngUrl)) return;
    scene.load.atlas(atlas.pngUrl, atlas.pngUrl, atlas.jsonUrl);
  });
}
`;
}

/**
 * Generates a pack-specific Phaser scene that recreates exported nodes.
 */
function buildSceneTs(props) {
    const { packName, packCamel, packFileName } = props;
    const packPascal = toPascalCase(packName);
    const sceneClassName = `${packPascal}Scene`;
    const preloadFunctionName = `preload${packPascal}Assets`;

    return `// This file is auto-generated by figma2assets plugin. Do not edit manually.
import { addAssetImage, addAssetNine } from "./utils";
import { ${packCamel}AutoAssets, ${packCamel}AutoAssetOrder, AutoAssetName, ${preloadFunctionName} } from "./${packFileName}-assets";

export class ${sceneClassName} extends Phaser.Scene {
  constructor() {
    super({ key: "${sceneClassName}" });
  }

  preload(): void {
    ${preloadFunctionName}(this);
  }

  create(): void {
    ${packCamel}AutoAssetOrder.forEach((assetName: AutoAssetName) => {
      const asset = ${packCamel}AutoAssets[assetName];
      if (asset.kind === "nine") {
        addAssetNine({ scene: this, asset });
        return;
      }
      addAssetImage({ scene: this, asset });
    });
  }
}

`;
}

/**
 * Resolves view child metadata against generated asset, view, and text entries.
 */
function buildViewEntries(manifest, assetEntries) {
    const assetsByFileName = new Map(assetEntries.map((entry) => [entry.frameName, entry]));
    const rawEntries = Array.isArray(manifest.views) ? manifest.views : [];
    const entriesByNodeId = new Map(rawEntries.map((entry) => [entry.nodeId, entry]));
    const entriesByFunctionName = new Map(rawEntries.map((entry) => [entry.functionName, entry]));

    return rawEntries.map((entry) => {
        const children = Array.isArray(entry.children)
            ? entry.children.map((child) => {
                const childType = child.type || "asset";

                if (childType === "view" || childType === "text") {
                    const childEntry =
                        entriesByNodeId.get(child.viewNodeId || child.textNodeId || child.nodeId) ||
                        entriesByFunctionName.get(child.viewFunctionName || child.textFunctionName);

                    if (!childEntry) return null;

                    const dataName = childEntry.dataName || `${childEntry.functionName}Data`;
                    if (childType === "view") {
                        return {
                            ...child,
                            type: "view",
                            viewKind: childEntry.kind,
                            viewName: childEntry.name,
                            viewFunctionName: childEntry.functionName,
                            viewDataName: dataName,
                        };
                    }

                    return {
                        ...child,
                        type: "text",
                        textName: childEntry.name,
                        textFunctionName: childEntry.functionName,
                    };
                }

                const assetEntry = assetsByFileName.get(child.assetFileName);
                if (!assetEntry) return null;

                return {
                    ...child,
                    type: "asset",
                    assetKey: assetEntry.assetKey,
                };
            }).filter(Boolean)
            : [];

        return {
            ...entry,
            dataName: entry.dataName || `${entry.functionName}Data`,
            children,
        };
    });
}

/**
 * Sorts generated view declarations so child view data exists before parents.
 */
function sortViewEntriesForDeclarations(viewEntries) {
    const entriesByFunctionName = new Map(viewEntries.map((entry) => [entry.functionName, entry]));
    const visiting = new Set();
    const visited = new Set();
    const result = [];

    function visit(entry) {
        if (!entry || visited.has(entry.functionName)) return;
        if (visiting.has(entry.functionName)) return;

        visiting.add(entry.functionName);

        entry.children
            .filter((child) => child.type === "view")
            .forEach((child) => {
                visit(entriesByFunctionName.get(child.viewFunctionName));
            });

        visiting.delete(entry.functionName);
        visited.add(entry.functionName);
        result.push(entry);
    }

    viewEntries.forEach((entry) => {
        visit(entry);
    });

    return result;
}

/**
 * Генерирует значение одного child внутри children object.
 */
function buildViewChildBlock(child, packCamel) {
    if (child.type === "view") {
        return `{\n      type: "view",\n      view: ${child.viewDataName},\n      x: ${Number(child.x || 0)},\n      y: ${Number(child.y || 0)},\n      width: ${Number(child.width || 0)},\n      height: ${Number(child.height || 0)},\n    }`;
    }

    if (child.type === "text") {
        return `{\n      type: "text",\n      text: ${packCamel}Texts[${JSON.stringify(String(child.textName || child.name || ""))}],\n      x: ${Number(child.x || 0)},\n      y: ${Number(child.y || 0)},\n      width: ${Number(child.width || 0)},\n      height: ${Number(child.height || 0)},\n    }`;
    }

    return `{\n      asset: ${packCamel}AutoAssets.${child.assetKey},\n      x: ${Number(child.x || 0)},\n      y: ${Number(child.y || 0)},\n      width: ${Number(child.width || 0)},\n      height: ${Number(child.height || 0)},\n    }`;
}

/**
 * Converts a text style snapshot into generated TS object literal.
 */
function buildTextStyleLiteral(style) {
    const snapshot = style && typeof style === "object" ? style : {};
    const lines = [];

    if (snapshot.fontFamily) {
        lines.push(`    fontFamily: ${JSON.stringify(String(snapshot.fontFamily))},`);
    }

    if (snapshot.fontSize !== undefined && snapshot.fontSize !== null && Number.isFinite(Number(snapshot.fontSize))) {
        lines.push(`    fontSize: ${Number(snapshot.fontSize)},`);
    }

    if (snapshot.color) {
        lines.push(`    color: ${JSON.stringify(String(snapshot.color))},`);
    }

    if (snapshot.stroke) {
        lines.push(`    stroke: ${JSON.stringify(String(snapshot.stroke))},`);
    }

    if (snapshot.strokeThickness !== undefined && snapshot.strokeThickness !== null && Number.isFinite(Number(snapshot.strokeThickness))) {
        lines.push(`    strokeThickness: ${Number(snapshot.strokeThickness)},`);
    }

    if (lines.length === 0) {
        return "{}";
    }

    return `{\n${lines.join("\n")}\n  }`;
}

/**
 * Converts base text into a locale map literal.
 */
function buildTextLocaleMapLiteral(baseText) {
    const value = JSON.stringify(String(baseText || ""));
    return `{\n  en: ${value},\n  ru: ${value},\n}`;
}

/**
 * Returns true if any generated view contains direct text children.
 */
function hasTextChildren(viewEntries) {
    return viewEntries.some((view) =>
        Array.isArray(view.children) && view.children.some((child) => child.type === "text")
    );
}

/**
 * Returns true if any generated view contains direct asset children.
 */
function hasAssetChildren(viewEntries) {
    return viewEntries.some((view) =>
        Array.isArray(view.children) && view.children.some((child) => (child.type || "asset") === "asset")
    );
}

/**
 * Returns true if any generated view contains direct nested view children.
 */
function hasViewChildren(viewEntries) {
    return viewEntries.some((view) =>
        Array.isArray(view.children) && view.children.some((child) => child.type === "view")
    );
}

/**
 * Generates one text data object field.
 */
function buildTextObjectField(entry) {
    const styleLiteral = buildTextStyleLiteral(entry.textStyle);
    const localeMapLiteral = buildTextLocaleMapLiteral(entry.baseText);

    return `  ${buildObjectKey(entry.name)}: {\n    name: ${JSON.stringify(String(entry.name || ""))},\n    x: ${Number(entry.x || 0)},\n    y: ${Number(entry.y || 0)},\n    width: ${Number(entry.width || 0)},\n    height: ${Number(entry.height || 0)},\n    localeMap: ${localeMapLiteral.replace(/\n/g, "\n    ")},\n    style: ${styleLiteral.replace(/\n/g, "\n  ")},\n  },`;
}

/**
 * Генерирует view data без явной TS-аннотации, чтобы IDE видела поля children.
 */
function buildViewDataLiteral(view, packCamel) {
    const childBlocks = view.children.map((child) => {
        return `    ${buildObjectKey(child.name)}: ${buildViewChildBlock(child, packCamel)},`;
    });
    const buttonLine = view.button ? "\n  button: true," : "";

    return `{\n  name: ${JSON.stringify(String(view.name || ""))},${buttonLine}\n  width: ${Number(view.width || 0)},\n  height: ${Number(view.height || 0)},\n  children: {\n${childBlocks.join("\n")}\n  },\n}`;
}

/**
 * Builds a large generated section header.
 */
function buildSectionHeader(title) {
    return `/**************\n *\n * ${title}\n *\n **************/`;
}

/**
 * Создает уникальное локальное имя переменной внутри generated function.
 */
function createUniqueLocalName(rawName, used, nameSuffix = "Child") {
    const base = toCamelCase(rawName) || "child";
    let next = `${base}${nameSuffix}`;
    let index = 2;

    while (used.has(next)) {
        next = `${base}${nameSuffix}${index}`;
        index += 1;
    }

    used.add(next);
    return next;
}

/**
 * Converts an already-safe generated identifier to PascalCase without re-normalizing it.
 */
function capitalizeIdentifier(identifier) {
    const value = String(identifier || "");
    return value.charAt(0).toUpperCase() + value.slice(1);
}

/**
 * Генерирует блок data-констант без общего типа у каждой константы.
 */
function buildViewConstantsBlock(viewEntries, packCamel) {
    const blocks = viewEntries.map((view) => {
        return `export const ${view.dataName} = ${buildViewDataLiteral(view, packCamel)};`;
    });

    return `${buildSectionHeader("CONSTANTS")}\n\n${blocks.join("\n\n")}`;
}

/**
 * Finds top-level generated view entries for section grouping.
 */
function findRootViewEntries(viewEntries) {
    const referencedFunctionNames = new Set();

    viewEntries.forEach((view) => {
        if (!Array.isArray(view.children)) return;

        view.children.forEach((child) => {
            if (child.type !== "view") return;
            if (!child.viewFunctionName) return;
            referencedFunctionNames.add(child.viewFunctionName);
        });
    });

    return viewEntries.filter((view) => !referencedFunctionNames.has(view.functionName));
}

/**
 * Collects nested view/button entries for one root section.
 */
function collectNestedViewEntries(root, entriesByFunctionName) {
    const result = [];
    const seen = new Set();

    function visit(entry) {
        if (!entry || !Array.isArray(entry.children)) return;

        entry.children.forEach((child) => {
            if (child.type !== "view") return;

            const childEntry = entriesByFunctionName.get(child.viewFunctionName);
            if (!childEntry) return;

            if (!seen.has(childEntry.functionName)) {
                seen.add(childEntry.functionName);
                result.push(childEntry);
            }
            visit(childEntry);
        });
    }

    visit(root);
    return result;
}

/**
 * Builds parent-prefixed helper names for nested view/button functions.
 */
function buildNestedHelperNames(root, nestedEntries) {
    const used = new Set([root.functionName]);
    const result = new Map();

    nestedEntries.forEach((entry) => {
        const base = `${root.functionName}${capitalizeIdentifier(entry.functionName) || "View"}`;
        let next = base;
        let suffix = 2;

        while (used.has(next)) {
            next = `${base}${suffix}`;
            suffix += 1;
        }

        used.add(next);
        result.set(entry.functionName, next);
    });

    return result;
}

/**
 * Генерирует child без промежуточной data-переменной: layout-математика должна быть видна сразу.
 */
function buildExpandedChildLines(child, parentDataName, helperNamesByFunctionName, usedLocalNames) {
    const childDataRef = buildObjectAccess(`${parentDataName}.children`, child.name);
    const childVarName = createUniqueLocalName(child.name, usedLocalNames);

    if (child.type === "view") {
        const helperName = helperNamesByFunctionName.get(child.viewFunctionName);

        return `  const ${childVarName} = ${helperName}(scene);\n  setLeftTop(\n    ${childVarName},\n    ${childDataRef}.x - ${parentDataName}.width / 2,\n    ${childDataRef}.y - ${parentDataName}.height / 2,\n  );\n  view.add(${childVarName});`;
    }

    if (child.type === "text") {
        return `  const ${childVarName} = createTextChild(scene, ${childDataRef});\n  setLeftTop(\n    ${childVarName},\n    ${childDataRef}.x - ${parentDataName}.width / 2,\n    ${childDataRef}.y - ${parentDataName}.height / 2,\n  );\n  view.add(${childVarName});`;
    }

    return `  const ${childVarName} = createAssetChild(scene, ${childDataRef});\n  setLeftTop(\n    ${childVarName},\n    ${childDataRef}.x - ${parentDataName}.width / 2,\n    ${childDataRef}.y - ${parentDataName}.height / 2,\n  );\n  view.add(${childVarName});`;
}

/**
 * Builds one expanded view/button creation function.
 */
function buildExpandedViewFunction(props) {
    const { functionName, view, helperNamesByFunctionName } = props;
    const usedLocalNames = new Set();
    const childBlocks = Array.isArray(view.children)
        ? view.children.map((child) =>
            buildExpandedChildLines(child, view.dataName, helperNamesByFunctionName, usedLocalNames)
        )
        : [];
    const childSection = childBlocks.length > 0 ? `\n\n${childBlocks.join("\n\n")}` : "";

    return `export function ${functionName}(scene: Phaser.Scene): Phaser.GameObjects.Container {\n  const view = createContainerFromViewData(scene, ${view.dataName});${childSection}\n\n  return view;\n}`;
}

/**
 * Builds one root view section with parent-prefixed nested helpers.
 */
function buildViewSection(root, entriesByFunctionName) {
    const nestedEntries = collectNestedViewEntries(root, entriesByFunctionName);
    const helperNamesByFunctionName = buildNestedHelperNames(root, nestedEntries);
    const functions = [
        buildExpandedViewFunction({
            functionName: root.functionName,
            view: root,
            helperNamesByFunctionName,
        }),
        ...nestedEntries.map((entry) =>
            buildExpandedViewFunction({
                functionName: helperNamesByFunctionName.get(entry.functionName),
                view: entry,
                helperNamesByFunctionName,
            })
        ),
    ];

    return `${buildSectionHeader(`VIEW: ${root.functionName}`)}\n\n${functions.join("\n\n")}`;
}

/**
 * Generates [packName].view.ts with declarative constants and expanded view functions.
 */
function buildViewsTs(props) {
    const { packCamel, packFileName, viewEntries } = props;
    const resolvedEntries = sortViewEntriesForDeclarations(
        (Array.isArray(viewEntries) ? viewEntries : []).filter((entry) => entry.kind !== "text")
    );
    const entriesByFunctionName = new Map(resolvedEntries.map((entry) => [entry.functionName, entry]));
    const rootEntries = findRootViewEntries(resolvedEntries);
    const assetImportBlock = hasAssetChildren(resolvedEntries)
        ? `import { ${packCamel}AutoAssets } from "./${packFileName}-assets";\n`
        : "";
    const textImportBlock = hasTextChildren(resolvedEntries)
        ? `import { ${packCamel}Texts } from "./${packFileName}.text";\n`
        : "";
    const utilsImports = [
        "createContainerFromViewData",
        ...(hasAssetChildren(resolvedEntries) ? ["createAssetChild"] : []),
        ...(hasTextChildren(resolvedEntries) ? ["createTextChild"] : []),
        ...(hasAssetChildren(resolvedEntries) || hasTextChildren(resolvedEntries) || hasViewChildren(resolvedEntries) ? ["setLeftTop"] : []),
    ];
    const constantsBlock = buildViewConstantsBlock(resolvedEntries, packCamel);
    const viewSections = rootEntries.map((root) => buildViewSection(root, entriesByFunctionName));

    return `// This file is auto-generated by figma2assets plugin. Do not edit manually.
${assetImportBlock}${textImportBlock}import {
  ${utilsImports.join(",\n  ")}
} from "./utils";

${constantsBlock}

${viewSections.join("\n\n")}
`;
}

/**
 * Generates [packName].text.ts with a single text data registry.
 */
function buildTextTs(props) {
    const { packCamel, textEntries } = props;
    const resolvedEntries = Array.isArray(textEntries) ? textEntries.filter((entry) => entry.kind === "text") : [];

    if (resolvedEntries.length === 0) {
        return null;
    }

    const textFields = resolvedEntries.map((entry) => buildTextObjectField(entry));

    return `// This file is auto-generated by figma2assets plugin. Do not edit manually.
import { IAutoTextData } from "./types";

export const ${packCamel}Texts: { readonly [name: string]: IAutoTextData } = {
${textFields.join("\n")}
};
`;
}

/**
 * Generates types.ts, utils.ts, [pack]-assets.ts, [pack]-scene.ts, and renderable view/text factories.
 */
function buildPhaserSceneSources(props) {
    const { packName, manifest, atlasBasePath } = props;
    const packCamel = toCamelCase(packName);
    const packFileName = sanitizePackName(packName);
    const atlasPngUrl = buildAtlasFilePath(atlasBasePath, `${packName}.png`);
    const atlasJsonUrl = buildAtlasFilePath(atlasBasePath, `${packName}.json`);
    const entries = buildAssetEntries(manifest);
    const renderableEntries = buildViewEntries(manifest, entries);

    return {
        assetsTs: buildAssetsTs({
            entries,
            packName,
            packCamel,
            atlasPngUrl,
            atlasJsonUrl,
        }),
        sceneTs: buildSceneTs({
            packName,
            packCamel,
            packFileName,
        }),
        viewTs: buildViewsTs({
            packName,
            packCamel,
            packFileName,
            viewEntries: renderableEntries,
        }),
        textTs: buildTextTs({
            packName,
            packCamel,
            packFileName,
            textEntries: renderableEntries,
        }),
    };
}

